export function useTranslations(lang: Lang) {
  return (key: UIKey) => ui[lang][key];
}

export function localePath(lang: Lang, path = '/') {
  const clean = path === '/' ? '' : path;
  return lang === defaultLang ? clean || '/' : `/${lang}${clean}`;
}
